-- Generic multi-project notification engine. Schema is set by spring.flyway.default-schema.

CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL,
    name VARCHAR(200) NOT NULL,
    status VARCHAR(16) NOT NULL,
    default_sender_email VARCHAR(320),
    ses_config_set VARCHAR(128),
    sms_sender_id VARCHAR(16),
    sms_entity_id VARCHAR(64),
    rate_limit_per_min INTEGER NOT NULL,
    daily_quota INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_projects_code UNIQUE (code)
);

CREATE TABLE project_api_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    key_hash VARCHAR(64) NOT NULL,
    key_prefix VARCHAR(12) NOT NULL,
    label VARCHAR(100) NOT NULL,
    scopes VARCHAR(200) NOT NULL,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_used_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_api_keys_hash UNIQUE (key_hash),
    CONSTRAINT fk_api_keys_project FOREIGN KEY (project_id) REFERENCES projects (id)
);
CREATE INDEX idx_api_keys_project ON project_api_keys (project_id);

CREATE TABLE notification_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    code VARCHAR(100) NOT NULL,
    channel VARCHAR(16) NOT NULL,
    locale VARCHAR(16) NOT NULL,
    version INTEGER NOT NULL,
    subject VARCHAR(300),
    body_html VARCHAR(20000),
    body_text VARCHAR(5000),
    dlt_template_id VARCHAR(64),
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_templates UNIQUE (project_id, code, channel, locale, version),
    CONSTRAINT fk_templates_project FOREIGN KEY (project_id) REFERENCES projects (id)
);

CREATE TABLE notifications (
    id UUID PRIMARY KEY,
    project_id BIGINT NOT NULL,
    request_id VARCHAR(64) NOT NULL,
    recipient_ref VARCHAR(128) NOT NULL,
    recipient_email VARCHAR(320),
    recipient_phone VARCHAR(32),
    type VARCHAR(64) NOT NULL,
    category VARCHAR(24) NOT NULL,
    channel VARCHAR(16) NOT NULL,
    template_code VARCHAR(100) NOT NULL,
    locale VARCHAR(16) NOT NULL,
    template_version INTEGER,
    priority VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL,
    variables_json VARCHAR(4000),
    title VARCHAR(300),
    body VARCHAR(5000),
    correlation_id VARCHAR(64),
    idempotency_key VARCHAR(200),
    attempts INTEGER NOT NULL,
    next_attempt_at TIMESTAMP WITH TIME ZONE,
    processing_started_at TIMESTAMP WITH TIME ZONE,
    last_error_code VARCHAR(100),
    retryable BOOLEAN NOT NULL,
    provider_message_id VARCHAR(200),
    expires_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at TIMESTAMP WITH TIME ZONE,
    read_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_notifications_idempotency UNIQUE (project_id, idempotency_key),
    CONSTRAINT fk_notifications_project FOREIGN KEY (project_id) REFERENCES projects (id)
);
CREATE INDEX idx_notifications_project_created ON notifications (project_id, created_at);
CREATE INDEX idx_notifications_recipient ON notifications (project_id, recipient_ref, created_at);
CREATE INDEX idx_notifications_due ON notifications (status, next_attempt_at);
CREATE INDEX idx_notifications_request ON notifications (project_id, request_id);

CREATE TABLE notification_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id UUID NOT NULL,
    attempt_no INTEGER NOT NULL,
    provider VARCHAR(32) NOT NULL,
    outcome VARCHAR(24) NOT NULL,
    error_code VARCHAR(100),
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_attempts_notification FOREIGN KEY (notification_id) REFERENCES notifications (id)
);
CREATE INDEX idx_attempts_notification ON notification_attempts (notification_id);

CREATE TABLE notification_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id UUID NOT NULL,
    from_status VARCHAR(16),
    to_status VARCHAR(16) NOT NULL,
    detail_code VARCHAR(100),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_events_notification FOREIGN KEY (notification_id) REFERENCES notifications (id)
);
CREATE INDEX idx_events_notification ON notification_events (notification_id);

CREATE TABLE notification_preferences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    user_ref VARCHAR(128) NOT NULL,
    channel VARCHAR(16) NOT NULL,
    category VARCHAR(24) NOT NULL,
    enabled BOOLEAN NOT NULL,
    consent_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_preferences UNIQUE (project_id, user_ref, channel, category),
    CONSTRAINT fk_preferences_project FOREIGN KEY (project_id) REFERENCES projects (id)
);

CREATE TABLE otp_challenges (
    id UUID PRIMARY KEY,
    project_id BIGINT NOT NULL,
    recipient_hash VARCHAR(64) NOT NULL,
    purpose VARCHAR(64) NOT NULL,
    channel VARCHAR(16) NOT NULL,
    salt VARCHAR(64) NOT NULL,
    code_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    attempts INTEGER NOT NULL,
    max_attempts INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    consumed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_otp_project FOREIGN KEY (project_id) REFERENCES projects (id)
);
CREATE INDEX idx_otp_recipient ON otp_challenges (project_id, recipient_hash, created_at);

CREATE TABLE device_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    user_ref VARCHAR(128) NOT NULL,
    platform VARCHAR(16) NOT NULL,
    token VARCHAR(512) NOT NULL,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_device_tokens UNIQUE (project_id, token),
    CONSTRAINT fk_device_project FOREIGN KEY (project_id) REFERENCES projects (id)
);
CREATE INDEX idx_device_user ON device_tokens (project_id, user_ref);
